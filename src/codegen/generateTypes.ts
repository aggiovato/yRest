import type { Data, FieldDef, Relations, SchemaBlock } from "../storage/types.js";

/** Input for {@link generateTypes}: the parsed pieces of a `db.yml` file. */
export type GenerateTypesInput = {
  /** Collections and their items. */
  data: Data;
  /** Field-level declarations from `_schema` (optional). */
  schema?: SchemaBlock;
  /** Relations from `_rel` — used to annotate FK fields (optional). */
  relations?: Relations;
};

/** Options for {@link generateTypes}. */
export type GenerateTypesOptions = {
  /** Source file name shown in the header comment (e.g. `"db.yml"`). */
  source?: string;
};

const HEADER = "// Auto-generated by yrest types — do not edit manually.";
const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const MAX_DEPTH = 4;

/**
 * Generates TypeScript declarations from a yrest dataset.
 *
 * - One `interface` per collection, named in singular PascalCase (`post_tags` → `PostTag`).
 * - Types are inferred from **all** items; a field missing on any item is optional.
 * - `_schema` declarations override inference (`_type`, `_required`, `_enum`, `_nullable`, `_items`)
 *   and add JSDoc (`_description`, `_format`, `_deprecated`).
 * - `_rel` many2one/one2one FK fields get a `FK → target.id` JSDoc note.
 * - Ends with a `CollectionName` union and a `Collections` map (`{ users: User[] }`).
 *
 * Output is deterministic: collections and fields keep their order of appearance.
 */
export function generateTypes(
  input: GenerateTypesInput,
  options: GenerateTypesOptions = {}
): string {
  const { data, schema = {}, relations = {} } = input;

  const collections = unique([...Object.keys(data), ...Object.keys(schema)]);
  const names = resolveInterfaceNames(collections);

  const out: string[] = [HEADER];
  if (options.source) out.push(`// Source: ${options.source}`);
  out.push("");

  for (const collection of collections) {
    out.push(
      renderInterface(
        names.get(collection)!,
        collection,
        data[collection] ?? [],
        schema[collection] ?? {},
        relations[collection] ?? {}
      )
    );
    out.push("");
  }

  out.push(`/** Union of all collection names in the source file. */`);
  out.push(
    collections.length > 0
      ? `export type CollectionName = ${collections.map((c) => quote(c)).join(" | ")};`
      : "export type CollectionName = never;"
  );
  out.push("");
  out.push(`/** Maps each collection name to its item array type. */`);
  out.push("export interface Collections {");
  for (const collection of collections) {
    out.push(`  ${propKey(collection)}: ${names.get(collection)}[];`);
  }
  out.push("}");

  return out.join("\n") + "\n";
}

// ── Interface rendering ──────────────────────────────────────────────────────

type FieldInfo = { values: unknown[]; count: number };

function renderInterface(
  name: string,
  collection: string,
  items: unknown[],
  fieldDefs: Record<string, FieldDef>,
  rels: Relations[string]
): string {
  const records = items.filter(isPlainObject);
  const fields = collectFields(records);
  const fieldNames = unique([...fields.keys(), ...Object.keys(fieldDefs)]);

  const lines: string[] = [`/** Item of the \`${collection}\` collection. */`];
  lines.push(`export interface ${name} {`);

  for (const field of fieldNames) {
    const info = fields.get(field);
    const def = fieldDefs[field];

    const inferredRequired =
      info !== undefined && info.count === records.length && records.length > 0;
    const required = def?.required ?? inferredRequired;

    let type = def ? typeFromDef(def, info) : typeOfValues(info!.values, 0);
    if (def?.nullable === true && !type.split(" | ").includes("null")) type = `${type} | null`;

    for (const doc of fieldDoc(field, def, rels)) lines.push(`  ${doc}`);
    lines.push(`  ${propKey(field)}${required ? "" : "?"}: ${type};`);
  }

  if (fieldNames.length === 0) lines.push("  [key: string]: unknown;");
  lines.push("}");
  return lines.join("\n");
}

/** Builds the JSDoc lines for a field: description + FK note as text, then tags. */
function fieldDoc(field: string, def: FieldDef | undefined, rels: Relations[string]): string[] {
  const text: string[] = [];
  const tags: string[] = [];
  if (def?.description) text.push(def.description.replace(/\*\//g, "*\\/"));

  const rel = Object.entries(rels).find(
    ([key, r]) => r.type !== "many2many" && (r.foreignKey ?? key) === field
  )?.[1];
  if (rel) text.push(`FK → ${rel.target}.id`);

  if (def?.format) tags.push(`@format ${def.format}`);
  if (def?.deprecated) tags.push("@deprecated");

  if (text.length === 0 && tags.length === 0) return [];
  if (tags.length === 0) return [`/** ${text.join(" — ")} */`];
  return ["/**", ...[...text, ...tags].map((l) => ` * ${l}`), " */"];
}

// ── Inference ────────────────────────────────────────────────────────────────

/** Collects every value seen per field across the records, preserving first-appearance order. */
function collectFields(records: Record<string, unknown>[]): Map<string, FieldInfo> {
  const fields = new Map<string, FieldInfo>();
  for (const record of records) {
    for (const [key, value] of Object.entries(record)) {
      let info = fields.get(key);
      if (!info) {
        info = { values: [], count: 0 };
        fields.set(key, info);
      }
      info.count++;
      info.values.push(value);
    }
  }
  return fields;
}

/**
 * Infers a single TS type for a list of values. Objects are merged into one shape and
 * array elements are pooled, so `[{a:1},{b:"x"}]` → `{ a?: number; b?: string }[]`.
 */
function typeOfValues(values: unknown[], depth: number): string {
  return unionOf(typeSetOf(values, depth));
}

function typeSetOf(values: unknown[], depth: number): Set<string> {
  const types = new Set<string>();
  const objects: Record<string, unknown>[] = [];
  const elements: unknown[] = [];
  let sawArray = false;

  for (const value of values) {
    if (value === null || value === undefined) types.add("null");
    else if (typeof value === "string") types.add("string");
    else if (typeof value === "number") types.add("number");
    else if (typeof value === "boolean") types.add("boolean");
    else if (Array.isArray(value)) {
      sawArray = true;
      elements.push(...value);
    } else if (isPlainObject(value)) objects.push(value);
    else types.add("unknown");
  }

  if (objects.length > 0) {
    types.add(depth >= MAX_DEPTH ? "Record<string, unknown>" : inlineObject(objects, depth + 1));
  }
  if (sawArray) {
    types.add(
      elements.length === 0
        ? "unknown[]"
        : depth >= MAX_DEPTH
          ? "unknown[]"
          : arrayOf(typeSetOf(elements, depth + 1))
    );
  }
  return types;
}

function inlineObject(records: Record<string, unknown>[], depth: number): string {
  const fields = collectFields(records);
  if (fields.size === 0) return "Record<string, unknown>";
  const props = [...fields].map(([key, info]) => {
    const optional = info.count < records.length ? "?" : "";
    return `${propKey(key)}${optional}: ${typeOfValues(info.values, depth)}`;
  });
  return `{ ${props.join("; ")} }`;
}

/** Joins a set of types into a union, dropping `unknown[]` when a concrete array is present. */
function unionOf(types: Set<string>): string {
  const list = [...types];
  if (list.length === 0) return "unknown";
  // A field only ever seen as `null` carries no type information.
  if (list.length === 1 && list[0] === "null") return "unknown";
  // `unknown[]` (empty array) is absorbed by any concrete array type.
  const hasConcreteArray = list.some((t) => t.endsWith("[]") && t !== "unknown[]");
  const filtered = hasConcreteArray ? list.filter((t) => t !== "unknown[]") : list;
  // Keep `null` last for readability.
  filtered.sort((a, b) => (a === "null" ? 1 : b === "null" ? -1 : 0));
  return filtered.join(" | ");
}

/** Wraps an element type set as an array type, parenthesising unions. */
function arrayOf(elements: Set<string>): string {
  const element = unionOf(elements);
  return element.includes(" | ") && elements.size > 1 ? `(${element})[]` : `${element}[]`;
}

// ── _schema overrides ────────────────────────────────────────────────────────

function typeFromDef(def: FieldDef, info: FieldInfo | undefined): string {
  if (def.enum && def.enum.length > 0) {
    return unique(def.enum.map((v) => literal(v))).join(" | ");
  }
  if (def.type) {
    if (def.type === "array") {
      const items = def.items;
      if (items?.enum && items.enum.length > 0)
        return arrayOf(new Set(items.enum.map((v) => literal(v))));
      if (items?.type) return arrayOf(new Set([primitiveFor(items.type)]));
      // Fall back to the inferred array type when it is an array.
      const inferred = info ? typeOfValues(info.values, 0) : "";
      return inferred.endsWith("[]") && !inferred.includes(" | ") ? inferred : "unknown[]";
    }
    return primitiveFor(def.type);
  }
  return info ? typeOfValues(info.values, 0) : "unknown";
}

function primitiveFor(type: NonNullable<FieldDef["type"]>): string {
  switch (type) {
    case "integer":
    case "number":
      return "number";
    case "string":
      return "string";
    case "boolean":
      return "boolean";
    case "array":
      return "unknown[]";
    case "object":
      return "Record<string, unknown>";
  }
}

function literal(value: unknown): string {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (value === null) return "null";
  return "unknown";
}

// ── Naming ───────────────────────────────────────────────────────────────────

/** Maps each collection to a unique interface name; falls back to plural on collision. */
function resolveInterfaceNames(collections: string[]): Map<string, string> {
  const names = new Map<string, string>();
  const used = new Set<string>();
  for (const collection of collections) {
    const words = splitWords(collection);
    const candidates = [
      toPascal([...words.slice(0, -1), singularize(words.at(-1) ?? "")]),
      toPascal(words),
    ];
    let name = candidates.find((c) => c && !used.has(c));
    if (!name) {
      const base = candidates[1] || "Collection";
      let i = 2;
      while (used.has(`${base}${i}`)) i++;
      name = `${base}${i}`;
    }
    if (/^[0-9]/.test(name)) name = `_${name}`;
    used.add(name);
    names.set(collection, name);
  }
  return names;
}

function splitWords(name: string): string[] {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
}

function toPascal(words: string[]): string {
  return words.map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join("");
}

/** Minimal English singularizer — covers the common collection naming patterns. */
export function singularize(word: string): string {
  const lower = word.toLowerCase();
  if (lower.length <= 2) return word;
  if (/(ss|us|is)$/.test(lower)) return word;
  if (/[^aeiou]ies$/.test(lower)) return word.slice(0, -3) + "y";
  if (/(s|x|z|ch|sh)es$/.test(lower)) return word.slice(0, -2);
  if (lower.endsWith("s")) return word.slice(0, -1);
  return word;
}

// ── Helpers ──────────────────────────────────────────────────────────────────

function propKey(key: string): string {
  return IDENT_RE.test(key) ? key : JSON.stringify(key);
}

function quote(value: string): string {
  return JSON.stringify(value);
}

function unique<T>(list: T[]): T[] {
  return [...new Set(list)];
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}
