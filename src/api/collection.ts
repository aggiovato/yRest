import type { Resource, YrestStorage } from "../storage/types.js";
import {
  createItem,
  deleteItem,
  findById as findItemById,
  patchItem,
} from "../services/resource.service.js";

/**
 * Typed CRUD access to one collection of a running yrest instance.
 *
 * Writes go through the same service layer as the REST routes, so they are visible to
 * HTTP clients immediately and persisted to `db.yml` exactly like a `POST` / `PATCH` /
 * `DELETE` (a no-op for in-memory data).
 *
 * Returned items are copies: mutating them does not change the stored data — use
 * {@link CollectionHandle.update} instead.
 *
 * @typeParam T - Item type, typically generated by `yrest types`.
 */
export interface CollectionHandle<T extends object = Resource> {
  /** Every item in the collection, in stored order. */
  findAll(): T[];
  /** The item with the given id, or `undefined`. Ids compare as strings (`1` matches `"1"`). */
  findById(id: string | number): T | undefined;
  /** Every item for which `predicate` returns `true`. */
  findWhere(predicate: (item: T) => boolean): T[];
  /** Number of items in the collection. */
  count(): number;
  /** Adds an item. The `id` is generated with the server's id strategy when omitted. */
  create(data: Omit<T, "id"> & { id?: unknown }): T;
  /** Merges `patch` into the item. The `id` cannot be changed. Returns `undefined` if not found. */
  update(id: string | number, patch: Partial<Omit<T, "id">>): T | undefined;
  /** Removes the item and returns it, or `undefined` if not found. */
  delete(id: string | number): T | undefined;
}

/** Function that returns a {@link CollectionHandle} for a collection name. */
export type CollectionAccessor = <T extends object = Resource>(name: string) => CollectionHandle<T>;

/**
 * Creates a {@link CollectionHandle} bound to `name`.
 *
 * @throws {Error} If the collection does not exist in the storage.
 */
export function createCollectionHandle<T extends object = Resource>(
  storage: YrestStorage,
  name: string,
  idStrategy: "increment" | "uuid" = "increment"
): CollectionHandle<T> {
  if (!storage.getCollection(name)) {
    const known = Object.keys(storage.getData()).join(", ") || "none";
    throw new Error(`Collection "${name}" does not exist (known collections: ${known})`);
  }

  const items = (): Resource[] => storage.getCollection(name) ?? [];
  const copy = (item: Resource | undefined): T | undefined =>
    item === undefined ? undefined : (structuredClone(item) as T);

  return {
    findAll: () => items().map((i) => copy(i)!),
    findById: (id) => copy(findItemById(items(), String(id))),
    findWhere: (predicate) =>
      items()
        .map((i) => copy(i)!)
        .filter(predicate),
    count: () => items().length,
    create: (data) => copy(createItem(storage, name, { ...(data as Resource) }, idStrategy))!,
    update: (id, patch) => {
      const rest: Resource = { ...(patch as Resource) };
      delete rest["id"];
      return copy(patchItem(storage, name, String(id), rest));
    },
    delete: (id) => copy(deleteItem(storage, name, String(id))),
  };
}

/** Builds a {@link CollectionAccessor} bound to a storage. */
export function collectionAccessor(
  storage: YrestStorage,
  idStrategy: "increment" | "uuid" = "increment"
): CollectionAccessor {
  return <T extends object = Resource>(name: string) =>
    createCollectionHandle<T>(storage, name, idStrategy);
}
